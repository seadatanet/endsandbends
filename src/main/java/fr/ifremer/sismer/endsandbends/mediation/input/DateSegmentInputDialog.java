    private Date dateFormatter(String formattedDate, String formattedTime)
            throws ParseException
    {
        Date retDate = null;
        UTCDateFormat isoSDF = new UTCDateFormat(SIMPLEDATE_TIMEFORMATMASK);
        retDate = isoSDF.parse(formattedDate + " " + formattedTime);
        return retDate;
    }

