    {
        jRadioButton_time.setSelected(_gapType == GAP_TYPE_TIME);
        jRadioButton_distance.setSelected(_gapType == GAP_TYPE_DIST);
    }

    /**
     * @see fr.ifremer.sismer.endsandbends.ui.OptionPage#updateData(boolean)
     */
    @Override
    public boolean updateData(boolean bSaveAndValidate)
    {
        Number value = (Number) _ctrlTimeLimit.getValue();
        if (value != null)
            _timeLimit = value.doubleValue();

        value = (Number) _ctrlDistanceLimit.getValue();
        if (value != null)
            _distanceLimit = value.doubleValue();

        value = (Number) _ctrlPointsLimit.getValue();
        if (value != null)
            _pointsLimit = value.intValue();

        return true;
    }

